def fahrenheit_to_celsius(fahrenheit: float) -> float:
    """Convert F to C."""
    return (fahrenheit - 32.0) * 5.0 / 9.0


def cube(x: float) -> float:
    """Compute the cube of x."""
    return x**3


def repeat(value: str) -> str:
    """Repeat a string thrice."""
    return value + value + value
